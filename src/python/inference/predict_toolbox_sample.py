if __name__ == '__main__':

    parser = argparse.ArgumentParser(
        description='Predict shape from radar Range-Angle heatmap'
    )
    parser.add_argument(
        '--file',
        type=str,
        default=None,
        metavar='FILE',
        help=(
            'Path to .mat heatmap file '
            '(stl_heatmap_*.mat or toolbox_sample_*.mat)'
        )
    )
    parser.add_argument(
        '--model',
        type=str,
        default='radar_shape_model_N16.pt',
        metavar='MODEL',
        help='Path to trained model .pt file (default: N16)'
    )
    parser.add_argument(
        '--batch',
        action='store_true',
        help=(
            'Predict all stl_heatmap_*.mat and '
            'toolbox_sample_*.mat files in current folder'
        )
    )
    args = parser.parse_args()

    if args.batch:
        # ── Batch mode ───────────────────────────────────────
        batch_predict(args.model)

    elif args.file:
        # ── Single file mode ─────────────────────────────────
        model, _  = load_model(args.model)
        heatmap, range_axis, ang_axis, true_shape = \
            load_heatmap(args.file)
        pred_name, confidence, all_probs, hm = \
            predict(heatmap, model)
        show_result(
            hm, pred_name, confidence, all_probs,
            true_shape  = true_shape,
            range_axis  = range_axis,
            ang_axis    = ang_axis,
            filename    = args.file,
        )

    else:
        # ── No arguments — show usage ─────────────────────────
        print("\nNo file specified. Examples:")
        print()
        print("  Single prediction:")
        print("    python predict_toolbox_sample.py "
              "--file stl_heatmap_circle_0deg.mat")
        print()
        print("  Different model:")
        print("    python predict_toolbox_sample.py "
              "--file stl_heatmap_square_0deg.mat "
              "--model radar_shape_model_N8.pt")
        print()
        print("  Batch — predict all heatmap files:")
        print("    python predict_toolbox_sample.py --batch")
        print()
        print("  Batch with specific model:")
        print("    python predict_toolbox_sample.py --batch "
              "--model radar_shape_model_N32.pt")
        print()

        # Auto-detect and run if exactly one heatmap file exists
        candidates = (glob.glob('stl_heatmap_*.mat') +
                      glob.glob('toolbox_sample_*.mat'))
        if len(candidates) == 1:
            print(f"Found one heatmap file: {candidates[0]}")
            print("Running prediction automatically...\n")
            model, _  = load_model(args.model)
            heatmap, range_axis, ang_axis, true_shape = \
                load_heatmap(candidates[0])
            pred_name, confidence, all_probs, hm = \
                predict(heatmap, model)
            show_result(
                hm, pred_name, confidence, all_probs,
                true_shape = true_shape,
                range_axis = range_axis,
                ang_axis   = ang_axis,
                filename   = candidates[0],
            )
        elif len(candidates) > 1:
            print(f"Found {len(candidates)} heatmap files.")
            print("Use --batch to predict all of them.")
